<p>Hardening (English word meaning hardening) Computer security is the process of securing a system by reducing vulnerabilities in it, this is achieved by eliminating software, services, users, etc. Unnecessary in the system and closing ports that are not in use as well as many other methods and techniques that will see during this brief summary introduction to Hardening systems.</p>

<p>Making life difficult for the attacker. That is the summary of the rationale for the Hardening of operating systems, you could say that is a set of activities that are carried out by the administrator of an operating system to enhance the maximum possible security of your computer. Its purpose, obstructing the work of the attacker and gain time in order to minimize the consequences of an imminent security incident and even, in some cases, prevent it entirely concrete.</p>

<p>One of the first things you need to make clear the Hardening of operating systems is not necessarily able to forge "invulnerable" teams. It is important to remember that, depending on the model of defense in depth , the host is only one layer of it. In other words, a factor to consider in the large number of points to be taken into account to defend "globally" system.</p>
