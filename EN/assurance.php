<p>Among the characteristics of a hardening process activities you can be counted as follows:</p>

<img src="../images/arr.png" alt="."> Configurations necessary to protect themselves from possible physical attacks or hardware of the machine.<br>
- The establishment of complex passwords for booting the computer and BIOS settings.<br>
- Disabling system boot to any drive other than your primary hard disk , and server cases.<br>
- Disabling Optical, USB or similar devices to prevent any entry of malware from an external storage medium.<br>
<img src="../images/arr.png" alt="."> Safe installation of the operating system, such as using a file system that has security features, and the concept of minimal installation, ie, avoiding the installation of any system component than necessary for the operation of the system.<br>
<img src="../images/arr.png" alt="."> Activation and / or appropriate service configuration automatic updates to ensure that the team will have all security patches that deliver the vendor a day.<br>
<img src="../images/arr.png" alt="."> Installation, configuration and maintenance of security software such as antivirus, antispyware, and antispam filter according to system needs.<br>

<br><p>Configuring the local system policy, considering several important points:</p>

<img src="../images/arr.png" alt="."> Policy robust passwords with caducables keys , historical storage of passwords (for not using cyclic passwords), account lockouts for failed attempts and password complexity requirements.<br>
<img src="../images/arr.png" alt="."> Rename and subsequent disablement standard system accounts.<br>
<img src="../images/arr.png" alt="."> Correct assignment of user rights, so to reduce the potential elevation of privilege, and always trying to limit the minimum privileges and / or rights of active users.<br>
<img src="../images/arr.png" alt="."> Setting general security options, such as those related to shared access routes, system shutdown, startup and logoff and network security options. <br>
<img src="../images/arr.png" alt="."> Restrictions software, based on the possible use of whitelisting software allowed more than blacklisting it.<br>
<img src="../images/arr.png" alt="."> Activation system audits, keys to a record of some characteristic attack attempts such as password guessing.<br>
<img src="../images/arr.png" alt="."> Configuring system services. At this point it is necessary to always try to disable all services that are not going to provide necessary functionality for system operation. For example, if your computer does not have wireless network cards, wireless network service should be disabled.<br>
<img src="../images/arr.png" alt="."> Setting network protocols. As far as possible, it is advisable to use systems Address Translation (NAT) to route internal teams within an organization. Disabling all those network protocols unnecessary in the system and limit the use thereof to a minimum. TCP / IP is a protocol that was not born thinking about safety, so limiting their use to strictly necessary is imperative.<br>
<img src="../images/arr.png" alt="."> Setting appropriate security permissions on files and folders on the system. As far as possible, explicitly deny any file permission to anonymous accounts or do not have access password. Set proper level permissions folders and files is key to avoid unwanted access to their content.<br>
<img src="../images/arr.png" alt="."> Setting security options of different programs, such as email clients, web browsers and in general any type of program that has interaction with the network.<br>
<img src="../images/arr.png" alt="."> Remote Access Setup. If not strictly necessary, it is good to disable remote access. However, when you need to have remote control of the machine, it must be set properly, restricting access to a limited number of users.<br>
<img src="../images/arr.png" alt="."> Proper configuration of user accounts, trying to work most of the time with limited access accounts and disabling administrator accounts. It is strongly recommended to use the impersonificación users to perform administrative tasks instead of log in as administrators.<br>
<img src="../images/arr.png" alt="."> File encryption units according to the needs of the system, considering an external storage for decryption keys. also consider the option of working with ciphers instant messaging and email.
