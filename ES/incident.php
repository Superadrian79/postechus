<p><b>(Incident Handling)</b> Este curso está diseñado para proporcionar las habilidades fundamentales para manejar y responder a los incidentes de seguridad en un sistema de información. El curso se dirige a diversos principios y técnicas subyacentes para detectar y responder a las amenazas de seguridad informática actual y emergente. Los estudiantes aprenderán cómo manejar varios tipos de incidentes, evaluación de riesgos, las metodologías y las diversas leyes y en relación con la gestión de incidentes de políticas. Después de asistir al curso, serán capaces de crear la gestión de incidentes y las políticas de respuesta y hacer frente a los distintos tipos de incidentes de seguridad informática.</p>
<p>El programa de formación de gestión de incidentes hará que los estudiantes competentes en el manejo y respuesta a varios incidentes de seguridad como incidentes de seguridad de la red, los incidentes de código malicioso y las amenazas de ataque de información privilegiada. Además, los estudiantes aprenderán acerca de su papel en el manejo y respuesta a los incidentes. El curso también cubre los equipos de respuesta a incidentes, métodos de entrenamiento de gestión de incidentes, y las técnicas de recuperación de incidentes en detalle. La certificación proporcionarán los profesionales una mayor aceptación de la industria como el administrador de incidentes experimentados.</p>

