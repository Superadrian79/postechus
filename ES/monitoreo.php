					<p style="text-align:center"><h3 class="blue">IT – INSIGHT ®</h3></p>

	<p class="blue">Solución integral de monitoreo de infraestructura, equipos y servicios.</p>

	<p>Su inversión en infraestructura representa un activo vital de la empresa y de la continuidad del negocio, el mantener esas aplicaciones y servicios en línea y disponibles representa cada día más esfuerzo por la complejidad y el crecimiento de los mismos.
Ambientes virtuales dinámicos, aplicaciones heredadas, aplicaciones en línea bajo distintas plataformas de desarrollo, soluciones de almacenamiento y toda una colección de dispositivos de red e infraestructura como routers, switches, puntos de acceso, y firewalls.
Es por ello que POSTECH ® ha desarrollado una de las herramientas de monitoreo más amigables y con mayores alcances en el mercado, el monitor IT – INSIGHT de Postech permite la revisión de componentes en la red de manera efectiva, y concentrando toda la información obtenida en tableros de reporteo gráficos organizados que permiten tener una vista rápida para la toma de decisiones, logrando así organizar, mapear y alertar complejos ambientes de monitoreo de Infraestructura y permitiendo alcanzar niveles de cumplimiento basado en estándares para alcanzar un monitoreo orientado a servicios.</p>

<p>IT-Insight es un sistema de monitorización de redes ampliamente utilizado, que vigila los equipos (hardware) y servicios (software) que se especifiquen, alertando cuando el comportamiento de los mismos no sea el deseado. Entre sus características principales figuran la monitorización de servicios de red (SMTP, POP3, HTTP, SNMP...), la monitorización de los recursos de sistemas hardware (carga del procesador, uso de los discos, memoria, estado de los puertos...), independencia de sistemas operativos, posibilidad de monitorización remota mediante túneles SSL cifrados o SSH, y la posibilidad de programar plugins específicos para nuevos sistemas.
Se trata de un software que proporciona una gran versatilidad para consultar prácticamente cualquier parámetro de interés de un sistema, y genera alertas, que pueden ser recibidas por los responsables correspondientes mediante (entre otros medios) correo electrónico y mensajes SMS, cuando estos parámetros exceden de los márgenes definidos por el administrador de red.</p>

<p><img class="img-responsive" src="../images/it01.png" alt="sistema de monitorización de redes"></p>

<p class="blue">Reto para los administradores de TIC’s</p>

<p>El reto para los administradores de las tecnologías de información y comunicación de las empresas hoy día es el lograr mantener sus servicios y aplicaciones disponibles el mayor tiempo posible logrando alcanzar así, acuerdos de servicio más elevados con los usuarios o con las organizaciones a las que sirven. Para soportar estas, cada vez más complejas infraestructuras es necesario tener vistas de negocio que permitan a los administradores de TIC´s entender la visión de las áreas de negocio de la organización, permitiendo así entregar un tablero de monitoreo que no solo representen el estado que guardan los componentes de la infraestructura, sino que además permiten entregar el estado que guardan los procesos del negocio, y de esta manera es más efectivo el monitoreo porque permite integrar estos procesos a los componentes de infraestructura de los cuales depende.</p>


