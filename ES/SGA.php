							<div class="toggle faq faq-miscellaneous">
								<div class="togglet"><i class="toggle-closed icon-question-sign"></i><i class="toggle-open icon-comment"></i>DNS Forwarder</div>
									<div class="togglec" style="text-align: justify;">Responde a las peticiones DNS de los clientes, y a su vez trata de resolver las consultas que usan todos los servidores DNS configurados actualmente disponibles. De esta manera, no es necesario configurar los servidores DNS públicos directamente en los sistemas cliente. Si se habilita este servicio, la dirección IP de la interfaz interna para Security Gateway Appliance (SGA) se entregará a los clientes DHCP como un servidor DNS. Si está desactivada, los servidores DNS configurados en Security Gateway Appliance (SGA) serán entregados en su lugar. Este servicio puede registrar nombres de host de DHCP, concede tal forma que nombres locales pueden ser resueltos a través de DNS. El mismo se puede hacer con las asignaciones de DHCP estáticos. Esto sólo debe estar habilitado en redes en las que los nombres de host de cliente se puede confiar.</div>
							</div>

							<div class="toggle faq faq-miscellaneous">
								<div class="togglet"><i class="toggle-closed icon-question-sign"></i><i class="toggle-open icon-comment"></i>Dynamic DNS</div>
									<div class="togglec" style="text-align: justify;">Actualiza un proveedor externo con la dirección IP pública actual en el servidor. Esto mantiene un nombre de host DNS constante, incluso si la dirección IP cambia periódicamente. Hay muchos servicios de DynDNS libres por ahí, Security Gateway Appliance (SGA) es compatible con más de 15 proveedores diferentes. Además de los servicios públicos normales, Security Gateway Appliance (SGA) también es compatible con RFC 2136 actualizaciones de DNS a los servidores DNS. En las versiones actualmente soportadas por Security Gateway Appliance (SGA), el cliente DynDNS es compatible con el uso de múltiples DynDNS y RFC 2136 clientes. Estos pueden ser usados ​​para actualizar múltiples servicios en la misma interfaz, o múltiples interfaces.</div>
