									<div class="togglec" style="text-align: justify;">Permite conexiones por medio de terminales de clientes PPPoE. Esto se puede utilizar como un medio para restringir el acceso de red en una interfaz restringida, ya sea cableada o inalámbrica. Protocolo de red para la encapsulación PPP sobre una capa de Ethernet. Es utilizada mayormente para proveer conexión de banda ancha mediante servicios de cable-módem y DSL. Este ofrece las ventajas del protocolo PPP como son la autenticación, cifrado, mantenimiento y compresión. En esencia, es un protocolo, que permite implementar una capa IP sobre una conexión entre dos puertos Ethernet, pero con las características de software del protocolo PPP, por lo que es utilizado para virtualmente "marcar" a otra máquina dentro de la red Ethernet, logrando una conexión "serial" con ella, con la que se pueden transferir paquetes IP, basado en las características del protocolo PPP.</div>
