								<div class="togglet"><i class="toggle-closed icon-question-sign"></i><i class="toggle-open icon-comment"></i>IPS</div>
									<div class="togglec" style="text-align: justify;">Controla el acceso de usuarios ilegítimos adicionando la posibilidad de bloquear los ataques, no simplemente de monitorearlos. Los IPS se categorizan según el modo en el que detectan el tráfico malicioso: Basado en firmas: compara el tráfico con firmas de ataques conocidos, debe tener la lista de firmas actualizada. Basado en políticas: se definen políticas de seguridad estrictas, si el tráfico está permitido el IPS permite el tráfico, si no lo está lo bloquea. Basado en anomalías: este método es el que más falsos positivos genera debido a que es muy difícil que es lo normal o estándar. En este modo encontramos dos opciones: Detección estadística de Anormalidades: analiza todo el trafico durante un tiempo determinado, luego de este tiempo crea una línea de lo que es “normal o estandar”. Luego de terminado este período si el comportamiento varía mucho en comparación a la regla creada, se toma como una posibilidad de ataque. Detección no Estadística de Anormalidades: en esta opción el Administrador define la línea de lo que es lo “normal o estándar” que va a ser la base para la comparación del tráfico. En resumen, el IPS agrega la posibilidad de bloquear ataques y además protege de forma proactiva la red, mientras que el IDS no permite bloquear y protege de forma reactiva la red.</div>
