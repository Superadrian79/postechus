									<div class="toggle faq faq-marketplace faq-authors">
										<div class="togglet"><i class="toggle-closed icon-question-sign"></i><i class="toggle-open icon-comment"></i>IDS</div>
										<div class="togglec" style="text-align: justify; display: none;">Sistema de detección de intrusos, como su nombre en inglés lo dice “Intrusion Detection System”, se utiliza para detectar accesos no permitidos a una red. El IDS posee sensores que les permite recopilar datos, de manera que cuando detecta el tráfico, puede determinar anomalías o comportamientos extraños los cuales pueden ser un ataque o un falso positivo. Tipos de IDS: <strong>HIDS: </strong>busca datos que hayan dejado los atacantes en un equipo cuando intentan tomar control del mismo, con toda la información que consiguen obtener genera sus estratégias. <strong>NIDS: </strong>IDS de red, detecta ataques a nivel de toda la red. Debe ver todo el tráfico que entra a la red. Tiene varias opciones para implementarlo, hardware, software o combinación de ambas.</div>
									</div>

									<div class="toggle faq faq-authors faq-miscellaneous">
									<div class="togglet"><i class="toggle-closed icon-question-sign"></i><i class="toggle-open icon-comment"></i>IPS</div>
										<div class="togglec" style="text-align: justify; display: none;">Controla el acceso de usuarios ilegítimos adicionando la posibilidad de bloquear los ataques, no simplemente de monitorearlos. Los IPS se categorizan según el modo en el que detectan el tráfico malicioso: Basado en firmas: compara el tráfico con firmas de ataques conocidos, debe tener la lista de firmas actualizada. Basado en políticas: se definen políticas de seguridad estrictas, si el tráfico está permitido el IPS permite el tráfico, si no lo está lo bloquea. Basado en anomalías: este método es el que más falsos positivos genera debido a que es muy difícil que es lo normal o estándar. En este modo encontramos dos opciones: Detección estadística de Anormalidades: analiza todo el trafico durante un tiempo determinado, luego de este tiempo crea una línea de lo que es “normal o estandar”. Luego de terminado este período si el comportamiento varía mucho en comparación a la regla creada, se toma como una posibilidad de ataque. Detección no Estadística de Anormalidades: en esta opción el Administrador define la línea de lo que es lo “normal o estándar” que va a ser la base para la comparación del tráfico. En resumen, el IPS agrega la posibilidad de bloquear ataques y además protege de forma proactiva la red, mientras que el IDS no permite bloquear y protege de forma reactiva la red.</div>
