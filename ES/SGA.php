								<div class="togglec" style="text-align: justify;">Failover (relevo) es cuando un equipo falla y es sustituido al menor tiempo posible para que este último continúe las acciones del que falló. Si algún servido falla, Security Gateway Appliance (SGA) enviará el tráfico a los servidores disponibles que estém con el servicio “arriba”.</div>
