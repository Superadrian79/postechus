								<div class="togglec" style="text-align: justify;">Sistema de detección de intrusos, como su nombre en inglés lo dice “Intrusion Detection System”, se utiliza para detectar accesos no permitidos a una red. El IDS posee sensores que les permite recopilar datos, de manera que cuando detecta el tráfico, puede determinar anomalías o comportamientos extraños los cuales pueden ser un ataque o un falso positivo. Tipos de IDS: <strong>HIDS: </strong>busca datos que hayan dejado los atacantes en un equipo cuando intentan tomar control del mismo, con toda la información que consiguen saca sus conclusiones. <strong>NIDS: </strong>IDS de red, detecta ataques a nivel de toda la red. Debe ver todo el tráfico que entra a la red. Tiene varias opciones para implementarlo, Hardware, software o combinación de ambas.</div>
