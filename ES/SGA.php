								<div class="togglet"><i class="toggle-closed icon-question-sign"></i><i class="toggle-open icon-comment"></i>DHCP Server</div>
									<div class="togglec" style="text-align: justify;">Entrega direcciones a los clientes DHCP y automáticamente configurarlos para acceso a la red, en nun rango asignado por el usuario. Por defecto, el servidor DHCP está activado en la interfaz LAN. El servicio del servidor DHCP, tiene una ficha para cada interfaz disponible. El proceso de DHCP sólo puede funcionar con interfaces con una dirección IP estática, por lo que si una ficha para una interfaz no está presente, compruebe que está habilitado y configurado con una dirección IP estática.</div>
