<p>Entre las actividades propias de un proceso de hardening se pueden contar las siguientes:</p>

<img src="../images/arr.png" alt="."> Configuraciones necesarias para protegerse de posibles ataques físicos o de hardware de la máquina.<br>
- El establecimiento de contraseñas complejas para el arranque del equipo y la configuración de la BIOS.<br>
- La deshabilitación de inicio de sistema para cualquier unidad que no sea el disco duro principal, y en casos de servidores.<br>
- La deshabilitación de dispositivos ópticos, usb o similares, para evitar cualquier entrada de malware desde un medio de almacenamiento externo.<br>
<img src="../images/arr.png" alt="."> Instalación segura del sistema operativo, como el uso de un sistema de archivos que tenga prestaciones de seguridad, y el concepto de instalación mínima, es decir, evitando la instalación de cualquier componente de sistema que no sea necesario para el funcionamiento del sistema.<br>
<img src="../images/arr.png" alt="."> Activación y/o configuración adecuada de servicios de actualizaciones automáticas, para asegurar que el equipo tendrá todos los parches de seguridad que entrega el proveedor al día.<br>
<img src="../images/arr.png" alt="."> Instalación, configuración y mantención de programas de seguridad tales como Antivirus, Antispyware, y un filtro Antispam según las necesidades del sistema.<br>

<br><p>Configuración de la política local del sistema, considerando varios puntos relevantes:</p>

<img src="../images/arr.png" alt="."> Política de contraseñas robusta, con claves caducables, almacenamiento histórico de contraseñas (para no usar contraseñas cíclicas), bloqueos de cuentas por intentos erróneos y requisitos de complejidad de contraseñas.<br>
<img src="../images/arr.png" alt="."> Renombramiento y posterior deshabilitación de cuentas estándar del sistema.<br>
<img src="../images/arr.png" alt="."> Asignación correcta de derechos de usuario, de tal manera de reducir las posibilidades de elevación de privilegios, y tratando siempre de limitar al mínimo los privilegios y/o derechos de los usuarios activos.<br>
<img src="../images/arr.png" alt="."> Configuración de opciones de seguridad generales, como aquellas relacionadas con rutas de acceso compartido, apagado de sistema, inicio y cierre de sesión y opciones de seguridad de red.<br>
<img src="../images/arr.png" alt="."> Restricciones de software, basado en lo posible en el uso de listas blancas de software permitido más que en listas negras del mismo.<br>
<img src="../images/arr.png" alt="."> Activación de auditorías de sistema, claves para tener un registro de algunos intentos de ataque característicos como la adivinación de contraseñas.<br>
<img src="../images/arr.png" alt="."> Configuración de servicios de sistema. En este punto es necesario tratar siempre de deshabilitar todos aquellos servicios que no vayan a prestar una funcionalidad necesaria para el funcionamiento del sistema. Por ejemplo, si su equipo no posee tarjetas de red inalámbrica, el servicio de redes inalámbricas debería estar deshabilitado.<br>
<img src="../images/arr.png" alt="."> Configuración de los protocolos de Red. En la medida de lo posible, es recomendable usar sistemas de traducción de direcciones (NAT) para direccionar los equipos internos de una organización. Deshabilitar todos aquellos protocolos de red innecesarios en el sistema y limitar el uso de los mismos al mínimo. TCP/IP es un protocolo que no nació pensando en seguridad, por lo que limitar su uso al estrictamente necesario es imperativo.<br>
<img src="../images/arr.png" alt="."> Configuración adecuada de permisos de seguridad en archivos y carpetas del sistema. En la medida de lo posible, denegar explícitamente cualquier permiso de archivo a las cuentas de acceso anónimos o que no tengan contraseña. Un correcto set de permisos a nivel de carpetas y archivos es clave para evitar acceso no deseado al contenido de los mismos.<br>
<img src="../images/arr.png" alt="."> Configuración de opciones de seguridad de los distintos programas, como clientes de correo electrónico, navegadores de internet y en general de cualquier tipo de programa que tenga interacción con la red.<br>
<img src="../images/arr.png" alt="."> Configuración de acceso remoto. En caso de no ser estrictamente necesario, es bueno deshabilitar el acceso remoto. Sin embargo, cuando es necesario tener control remoto de la máquina, es preciso configurarlo de manera adecuada, restringiendo el acceso a un número muy limitado de usuario.<br>
<img src="../images/arr.png" alt="."> Configuración adecuada de cuentas de usuario, tratando de trabajar la mayor parte del tiempo con cuentas de acceso limitado y deshabilitando las cuentas de administrador. Es absolutamente recomendable usar la impersonificación de usuarios para realizar labores administrativas en vez de iniciar sesión como administradores.<br>
<img src="../images/arr.png" alt="."> Cifrado de archivos o unidades según las necesidades del sistema, considerando un almacenamiento externo para las llaves de descifrado. Considerar además la opción de trabajar con sistemas de cifrado de mensajería instantánea y correo electrónico.
