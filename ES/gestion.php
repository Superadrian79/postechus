<p class="blue"><b>Sistema de Gestión de incidentes</b></p>

<p>La gestión de incidentes es un área de procesos perteneciente a la gestión de servicios de tecnologías de la información. El primer objetivo de la gestión de incidentes es recuperar el nivel habitual de funcionamiento del servicio y minimizar en todo lo posible el impacto negativo en la organización de forma que la calidad del servicio y la disponibilidad se mantengan</p>.

<p>Los incidentes que no pueden ser resueltos rápidamente por el equipo de ayuda al usuario, son asignados a un especialista del equipo de soporte técnico. La resolución del incidente debe ser ejecutada lo antes posible para restaurar el servicio rápidamente.</p>
<center><p><img class="img-responsive" src="../images/RTIR.jpg" alt="Sistema de Gestión de incidentes"></p></center>

<p>El proceso habitual de gestión de incidentes es el siguiente:</p>

<img src="../images/arr.png" alt="."> Detección y registro del incidente.<br>
<img src="../images/arr.png" alt="."> Clasificación y soporte inicial.<br>
<img src="../images/arr.png" alt="."> Investigación y diagnóstico.<br>
<img src="../images/arr.png" alt="."> Resolución y recuperación.<br>
<img src="../images/arr.png" alt="."> Cierre del incidente.<br>
<img src="../images/arr.png" alt="."> Monitorización, seguimiento y comunicación del incidente.<br><br>

<p>La correcta implementación de un sistema de gestión de incidentes, asi como la facil adecuacion de las deficniciones del mismo, permiten a las organizaciones de TI mantener una correcta entrega de servicios, logar el cumplimiento en apego a los marcos de referencia internacionales y cumplir o poder realizar compromisos de niveles de entrega de servicios y entregar las correctas metricas del mismo.</p>

<p>La solución de gestión de incidencias de Postech es indicado para servicios de mantenimiento, ayuda al usuario y seguimiento de incidencias de seguridad informatica para cualquier sector. Permite definir flujos de trabajo para abordar problemáticas derivadas de anomalías en servicios y equipos.</p>



<p class="blue"><b>Algunas de sus funcionalidades son:</b></p>

<p>Gestión de incidencias:</p>

<img src="../images/arr.png" alt="."> Recepción: via mail, entradas por el propio usuario, desde un formulario web etc. Abre de forma automática un expediente y avisa mediante notificación (interna, correo electrónico o SMS) al responsable.<br>
<img src="../images/arr.png" alt="."> Resolución: atención y cerrado inmediato o planificación en el tiempo según tipo o urgencia. Asignación de recursos. Re-asignación. Escalado. Listas con el estado y los responsables. Retrasos. Avisos automáticos a quien sea necesario. Posibilidad de aladir notas, documentos, correos, fotos, manuales. Búsquedas en base de datos de conocimiento. Busquedas indexadas en cualquier item, incluso dentro de los documentos. Introducción de horas y material utilizado. Facturación.<br>
<img src="../images/arr.png" alt="."> Control: generación y envío automático del resumen de la incidencia. Generación de informes y estadísticos por varios criterios: urgencia, tipo, contrato, elemento, técnico.. Informes de horas invertidas. Informe de elementos problemáticos. Filtros e informes por periodos, personas, clientes etc.<br><br>


<p class="blue"><b>Mantenimientos preventivos:</b></p>

<img src="../images/arr.png" alt="."> Planificación: posibilidad de lanzar mantenimientos preventivos de elementos o contratos con diversas periodicidades. semanal, mensual, trimestral anual etc.. Una vez lanzado, disponemos de tareas a realizar en determinados periodos. Podemos asignar técnicos, por defecto o mensualmente. Informes y listados de tareas a realizar en un periodo determinad.<br>
<img src="../images/arr.png" alt="."> Realización: avisos y listados de tareas a realizar. Gráficos GANTT. Reflejar tiempos utilizados y material. facturación y seguimiento administrativo. Adjuntar documentacion, correos electrónicos etc.<br>
<img src="../images/arr.png" alt="."> Control: informes de cada actuación realizada. envío automático. listados y estadísticos de trabajos realizados.<br><br>

<p class="blue"><b>Gestión de contratos y elementos. SLA :</b></p>

<img src="../images/arr.png" alt="."> Inventario: Elementos organizados por diferentes criterios: tipo, departamente, contratos etc.<br>
<img src="../images/arr.png" alt="."> SLA: posibilidad de guardar y controlar documentación relativa a los contratos y condiciones de servicio. Reealización de mantenimientos e intervenciones según las condiciones reflejado en las SLA (tiempos, urgencias, visibilidades).<br>
<img src="../images/arr.png" alt="."> Otros.<br>
<img src="../images/arr.png" alt="."> Agenda: base de datos de empresas y contactos.<br>
<img src="../images/arr.png" alt="."> Calendario actividades.<br>
<img src="../images/arr.png" alt="."> Mailing.<br><br>

<p class="blue"><b>Integración e-mail y SMS:</b></p>

<img src="../images/arr.png" alt="."> Notificaciones a terceros vía mail de acciones y tareas.<br>
<img src="../images/arr.png" alt="."> Recepción automática de mails. Envío SMS.<br>
<img src="../images/arr.png" alt="."> Enlaces: con la Gestión de Calidad o con la Gestión de proyectos. Enlaces con otros sistemas propios mediante desarrollos específicos: ERPs, BI, Blance Score Card etc.<br><br>

