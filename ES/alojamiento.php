<p class="blue"><b>Centro de datos</b></p>

<p>Contamos con nuestro propio Centro de Datos de Clase Mundial ubicado en el estado de Ohio en los Estados Unidos.
Tener el Centro datos en este país nos trae muchas ventajas entre las que encontramos:</p>

<img src="../images/arr.png" alt="."> Contar con un servicio confiable, seguro y veloz.<br>
<img src="../images/arr.png" alt="."> Tener una red Certificada en Cisco y el mejor equipo.<br>
<img src="../images/arr.png" alt="."> Menores costos de operación que nos permiten ofrecerle mejores precios.<br>
<img src="../images/arr.png" alt="."> Mayor velocidad de conexión y ancho de banda sumando un total de 135Mbps.<br>
<img src="../images/arr.png" alt="."> Quíntuple redundancia en nuestros enlaces que nos da más tiempo en línea Alta disponibilidad del 99.9% del año en línea, superior a la que es posible lograr en México por la mala calidad de los enlaces dedicados que se ofrecen.<br>
<img src="../images/arr.png" alt="."> Acceso a mejores tecnologías en forma inmediata que nos permite la mejora continúa.<br><br>

<p class="blue"><b>Conectividad</b></p>

<p>Nuestra red es de tránsito libre, esto significa que todas las rutas de Internet son vistas.El equipo central o core está ubicado en instalaciones neutrales en las cuales varios proveedores mayores de conexión (Carriers) tienen acceso a las instalaciones. Toda la red está conectada a dos routers Cisco 7513 con BGP para proveer el routeo y redundancia, de ahí se pasa a una serie de switches de capa 3 en donde se hacen los segmentos de red.</p>
<p>Estamos conectados a diversos proveedores de enlace dedicado como Cogent Co., ICG, Time Warner Telecom, Ameritech y XO Communications. De esta manera reducimos nuestros costos de transmisión de datos, podemos expandir nuestra red de forma efectiva, le damos a usted un mejor precio y servicio y evitamos molestas desconexiones de red al no depender de un sólo proveedor.</p>

<p class="blue"><b>Seguridad informática</b></p>

<p>Usamos únicamente equipo de red de Cisco, nuestro personal está certificado en Networking por The Cisco Networking Academy.
En la red contamos con un Sistema de Detección de Intrusos (IDS), Firewall y medidas de seguridad que nos permiten bloquear los constantes ataques de hackers y personas mal intencionadas. Además actualizamos frecuentemente todos los sistemas operativos de los servidores y realizamos pruebas de seguridad para asegurarnos de que las personas no deseadas se mantengan lejos de su sitio.</p>

<p class="blue"><b>Seguridad Física</b></p>

<p>El acceso físico a los servidores de un centro de datos debe estar bien resguardado y restringido. Para proteger nuestro equipo y su sitio contamos con cámaras de seguridad que cubren cada metro cuadrado de nuestras instalaciones. Estas cámaras están conectadas a una central de monitoreo 24 horas, y tiene conexión directa a la policía local que llega en menos de 3 minutos en caso de algún incidente.</p>
<p>La autentificación mediante huella digital es necesaria para abrir cualquiera de las puertas del centro de datos, esto nos permite controlar el acceso a cuartos de servidores y saber qué áreas se han visitado. Para hacer aún más seguras las instalaciones, tanto el centro de monitoreo de red como los cuartos de servidores están en el sótano y no cuentan con ventanas o acceso mediante ventilaciones.Además contamos con todos los sistemas de supresión y detección de fuego según las regulaciones del Estado.</p>

<p class="blue"><b>Personal en sitio 24 horas</b></p>

<p>Tenemos personal altamente capacitado trabajando físicamente en el Centro de Datos las 24 horas los 365 días del año.
Los Administradores y Técnicos que conforman el Staff del Centro de Datos son expertos en redes, seguridad informática, administración de servidores, mantenimiento de hardware y atención de emergencias.
<br>En combinación con nuestro Depto. de Soporte técnico emplean sus capacidades para asegurar la estabilidad y permanencia en línea de todos los sistemas.</p>


<p class="blue"><b>Respaldo y Planta Generadora de Energía Eléctrica</b></p>

<p>Para fallas de corriente menores contamos con un Sistema de Corriente Ininterrumpida APC que soportan todos los equipos y se activan en forma automática en milisegundos.<br>
Para cuando se extiende la falla eléctrica contamos con un generador diesel de corriente eléctrica marca Holt que es capaz de genera 850 Kilowatts, cantidad más que suficiente para mantener todos los equipos y la infraestructura de red durante más de 72 horas. En caso de una falla de corriente extensa (más de 72 horas), contamos con la posibilidad de recargar el combustible en un tiempo menor a 30 minutos. El generador realiza un chequeo automático dos veces por semana y un Ingeniero lo revisa físicamente una vez al mes para asegurar que se encuentre en óptimas condiciones.<br>
Toda la corriente eléctrica está conectada a un sistema acondicionador de línea eléctrica, el cual regula la corriente y la manda continua sin picos o variaciones de voltaje, esta medida protege los equipos y alarga su vida.</p>

<p>En el techo del edificio instalamos un sistema de Aire Acondicionado de APC de 15 toneladas que proporciona enfriamiento a las instalaciones.<br>

También contamos con otro sistema Liebert de 10 toneladas en el sótano, éste regula la atmósfera, es decir, controla el nivel de humedad, filtra las partículas suspendidas en el aire y mantiene a la misma temperatura los cuartos de servidores.<br>

Actualmente hospedamos más de 100 servidores, sin embargo nuestra capacidad instalada es para más de 250 servidores y la posibilidad de expandirse a más de 2000 servidores sin necesidad de construir más instalaciones.<br>
Nuestra red está utilizada en un 30% y por política de buen servicio siempre tenemos al menos el 25% de nuestro ancho de banda libre.
Las características del Edificio del Centro de Datos son:</p>

