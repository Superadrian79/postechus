<p class="blue"><b>Tecnicas y Herramientas para la evaluación de vulnerabilidades de la red</b></p>
 
<p>La palabra vulnerabilidad hace referencia a una debilidad en un sistema permitiendo a un atacante violar la confidencialidad, integridad, disponibilidad, control de acceso y consistencia del sistema o de sus datos y aplicaciones.
Las vulnerabilidades son el resultado de bugs o de fallos en el diseño del sistema. Aunque, en un sentido más amplio, también pueden ser el resultado de las propias limitaciones tecnológicas, porque, en principio, no existe sistema 100% seguro. Por lo tanto existen vulnerabilidades teóricas y vulnerabilidades reales (conocidas como exploits).</p>

<p>El análisis de la vulnerabilidad, a veces llamado exploración de la vulnerabilidad, es el acto de determinar qué agujeros y vulnerabilidades de la seguridad pueden ser aplicables a la red de la blanco. Para hacer esto, examinamos las máquinas identificadas dentro de la red de la blanco para identificar todos los puertos abiertos y los sistemas operativos y los usos que los anfitriones están funcionando (número de versión incluyendo, nivel del remiendo, y paquete del servicio). Además, comparamos esta información con varias bases de datos de la vulnerabilidad del Internet para comprobar qué vulnerabilidades y hazañas actuales pueden ser aplicables a la red de la blanco.</p>

<p>La evaluación de vulnerabilidades es un factor clave en la seguridad de la información en una compañía. Día a día se encuentran vulnerabilidades en diferentes Sistemas Operativos, Sistemas o Aplicaciones informáticas, Programa de correo electrónico, entre otros. Ningún tipo de red es totalmente intocable.</p>

