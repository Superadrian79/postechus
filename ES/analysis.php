<p class="blue"><b>Analisis de tráfico</b></p>

<p>Se llama análisis de tráfico al proceso de inferir información a partir de las características del tráfico de comunicación sin analizar la información que se intercambian los comunicantes. Para obtener información podemos basarnos por ejemplo en el origen y destino de las comunicaciones, su tamaño, su frecuencia, la temporización, patrones de comunicación, etc.</p>

<p>El análisis de tráfico está muy relacionado con el análisis de paquetes y se suelen usar de forma conjunta. En el análisis de paquetes se estudia la información contenida en los paquetes que circulan por la red y a partir de eso trata de inferir información.</p> 

<p>El análisis del tráfico infiere información a partir las características observables de los datos que circulan por la red. Por ejemplo, puede ser interesante el tamaño de los paquetes o la temporización de los mensajes. Este tipo de técnicas pueden ser utilizadas por atacantes para por ejemplo deducir tamaños de claves durante sesiones interactivas o para deducir el origen y destino de una comunicación. También puede ser utilizada por administradores de red para descubrir actividades potencialmente maliciosas.
Por tanto la seguridad informática se ocupa del estudio de las técnicas de análisis de tráfico y de contramedidas para protegernos de dicho tipo de técnicas.</p>

<p>El origen del análisis de tráfico se encuentra en el análisis de los tráficos de información que tradicionalmente se ha hecho para aplicaciones militares. Este tipo de sistemas tradicionalmente infieren información a partir del análisis de las señales de comunicación. Hoy día el análisis de tráfico es muy útil para inferir información a partir del tráfico que hay en las redes de comunicaciones.</p>

<p>Postech cuenta con una de las herramientas de análisis de tráfico más eficaces del mercado, utilizada para análisis de trafico de grandes volúmenes (Big data analytics), con aplicaciones para estándares de la industria de banca y aplicaciones de uso militar. Permite realizar el análisis en tiempo real de grandes volúmenes de información y poder realizar búsquedas semánticas dentro del contenido del mismo. Permitiendo realizar alertas relacionadas al contenido así como para descubrir actividades potencialmente maliciosas. Y por supuesto trafico que contenga código malicioso como virus, gusanos, backdoors, etc.</p>



