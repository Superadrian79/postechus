<p>Para entender de la mejor forma la idea de un SOC es necesario comprender que no se trata sólo de un servicio o proceso de monitoreo que todo esté bien o que los antivirus estén actualizados, va más allá y como lo plantean varios autores, la idea central de un SOC es gestionar el riesgo que pueda afectar la seguridad de la información y por ende la seguridad informática. 
Para que esto sea posible es necesario definir que lineamientos regirán al SOC, como se estructurará, que jerarquías se deben manejar y por supuesto, los alcances de las actividades a realizar.</p>



