<p class="blue"><b>Ingeniería para Respuesta a Incidentes – Network Security 3.0</b></p>


<p>Los ataques consumados a organizaciones de cualquier tamaño están aumentando considerablemente. Los hackers utilizan técnicas cada vez más sofisticadas con las que pueden violar la información de una Empresa ¡en minutos! ¡Conozca la forma en que lo hacen y utilice sus mismas armas para proteger su información!</p>

<p>El curso tiene como objetivo capacitar a los responsables de la Seguridad Informática de la Organización para que aprendan a blindar la Información de su Empresa utilizando las mismas Técnicas, Herramientas y metodologías usadas por atacantes reales (Hackers).</p>

