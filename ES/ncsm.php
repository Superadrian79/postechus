						<h3 class="blue">NCSM en Acción</h3><br>

						<h2>Detección de Ransomware</h2><br>

						<div class="justify">
							<p><b>Escenario: </b>Un empleado ejecuta un archivo malicioso de phishing.</p>
							<p><b>Sin NCSM: </b>El ransomware se comunica con su servidor C2, descarga el payload, y cifra archivos durante horas antes de ser detectado.</p>
							<p><b>Con NCSM: La comunicación inicial con el C2 dispara una alerta CRITICAL. El equipo SOC aísla el endpoint en minutos, antes de que el cifrado comience.</b></p>
						</div>

						<br><h2>Detección de Amenazas Internas</h2><br>

						<div class="justify">
							<p><b>Escenario: </b>Un empleado con acceso privilegiado comienza a exfiltrar datos antes de renunciar.</p>
							<p><b>Sin NCSM: </b>La transferencia masiva de datos pasa desapercibida porque usa canales "legítimos".</p>
							<p><b>Con NCSM: </b>El análisis de comportamiento detecta volúmenes de transferencia 500% superiores al baseline normal del usuario. Alerta silenciosa permite investigación sin alertar al empleado.</p>
						</div>

						<br><h2>Detección de Movimiento Lateral</h2><br>

						<div class="justify">
							<p><b>Escenario: </b>Un atacante compromete una estación de trabajo y se mueve hacia servidores críticos.</p>
							<p><b>Sin NCSM: </b>El firewall perimetral no ve tráfico interno. El atacante alcanza el servidor de base de datos sin ser detectado.</p>
							<p><b>Con NCSM: </b>Conexiones SMB/RDP inusuales entre la estación de trabajo y servidores generan alertas de movimiento lateral. El ataque se contiene antes de alcanzar datos sensibles.</p>
						</div>

